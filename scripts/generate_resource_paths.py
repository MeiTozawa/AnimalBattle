#!/usr/bin/env python3
"""
generate_resource_paths.py

Resource/ および Config/ 以下のファイルをスキャンし、
AnimalBattle/Asset/ResourcePath.g.cs を自動生成します。

パスはスクリプトの位置から自動解決されます。引数は不要です。

使用方法:
    python scripts/generate_resource_paths.py
"""

import sys
import os
import re
from pathlib import Path

# ---- パス設定 ---------------------------------------------------------------

_SCRIPT_DIR    = Path(__file__).resolve().parent
_PROJECT_ROOT  = _SCRIPT_DIR.parent
_RESOURCE_ROOT = _PROJECT_ROOT / "Resource"
_CONFIG_ROOT   = _PROJECT_ROOT / "Config"
_OUTPUT_FILE   = _PROJECT_ROOT / "AnimalBattle" / "ResourcePath.g.cs"


# ---- 識別子生成ヘルパー ------------------------------------------------------

def _to_pascal(text: str) -> str:
    """区切り文字を含む文字列を PascalCase 識別子に変換する。"""
    words = [w for w in re.split(r'[^a-zA-Z0-9]', text) if w]
    if not words:
        return ""
    return "".join(w.capitalize() for w in words)


def _file_to_identifier(file_name: str) -> list[str]:
    """
    ファイル名から C# 定数名（PascalCase）のリストを生成する。
    エイリアスが必要な場合は複数返す。
    """
    p = Path(file_name)
    stem = p.stem
    ext = p.suffix.lstrip(".").capitalize()

    identifiers: list[str] = []

    # 1_Cat_Idle-Sheet のような連番プレフィックスの処理
    m = re.match(r"^(\d+)_(.+)$", stem)
    if m:
        num, rest = m.groups()
        if re.match(r"^[a-zA-Z]", rest):
            identifiers.append(f"{_to_pascal(rest)}{ext}")
        else:
            # 027_3 などの数字のみのパターン
            identifiers.append(f"Character{num}{ext}")
            identifiers.append(f"Character{num}_{_to_pascal(rest)}{ext}")
    elif re.match(r"^\d", stem):
        # 先頭が数字
        identifiers.append(f"Character{_to_pascal(stem)}{ext}")
        if "_" in stem:
            # 027_3 -> Character027Png
            base_num = stem.split("_")[0]
            identifiers.append(f"Character{base_num}{ext}")
    else:
        name = _to_pascal(stem)
        identifiers.append(f"{name}{ext}")

    # 重複除去しつつ順序維持
    seen = set()
    result = []
    for item in identifiers:
        if item and item not in seen:
            seen.add(item)
            result.append(item)

    return result


# ---- ディレクトリスキャン ----------------------------------------------------

def _scan_directory(dir_path: Path) -> list[Path]:
    """指定ディレクトリ直下のファイルを名前順で取得する。"""
    if not dir_path.exists():
        return []
    return sorted([p for p in dir_path.iterdir() if p.is_file()])


def _scan_subdirectories(dir_path: Path) -> list[Path]:
    """指定ディレクトリ直下のサブディレクトリを名前順で取得する。"""
    if not dir_path.exists():
        return []
    return sorted([p for p in dir_path.iterdir() if p.is_dir()])


# ---- C# コード生成 -----------------------------------------------------------

def generate_code() -> str:
    lines: list[str] = [
        "// <auto-generated>",
        "// このファイルは scripts/generate_resource_paths.py によって自動生成されます。",
        "// 手動で編集しないでください。Resource/ または Config/ 以下のファイルを変更後、スクリプトを再実行してください。",
        "// </auto-generated>",
        "",
        "using System;",
        "",
        "namespace AnimalBattle;",
        "",
        "/// <summary>",
        "/// プロジェクト内の各種リソース（画像、スプライトシート、XML定義、TOML設定ファイル等）の相対パス定数を提供する自動生成静的クラス。",
        "/// <see cref=\"Core.Asset.AssetManager\"/> や <see cref=\"Configs.ConfigManager\"/> でのリソース指定を一元管理します。",
        "/// </summary>",
        "public static class ResourcePath",
        "{",
    ]

    # ---- 1. Resource/ 直下のサブディレクトリごとにクラスを生成 ----
    known_subdirs = ["Characters", "Platform", "Effects"]
    existing_subdirs = {d.name: d for d in _scan_subdirectories(_RESOURCE_ROOT)}

    for subdir_name in known_subdirs:
        subdir_path = existing_subdirs.get(subdir_name, _RESOURCE_ROOT / subdir_name)
        class_name = _to_pascal(subdir_name)

        lines.append(f"    /// <summary>")
        lines.append(f"    /// {subdir_name} リソースのパス定数。")
        lines.append(f"    /// </summary>")
        lines.append(f"    public static class {class_name}")
        lines.append(f"    {{")
        lines.append(f'        /// <summary>{subdir_name} リソースフォルダの相対パス。</summary>')
        lines.append(f'        public const string Directory = @"{subdir_name}";')

        files = _scan_directory(subdir_path)
        defined_keys: set[str] = set()

        for file_path in files:
            rel_file_path = f"{subdir_name}\\{file_path.name}"
            ids = _file_to_identifier(file_path.name)
            for const_id in ids:
                if const_id in defined_keys:
                    continue
                defined_keys.add(const_id)
                lines.append("")
                lines.append(f'        /// <summary>{file_path.name} のファイルパス。</summary>')
                lines.append(f'        public const string {const_id} = @"{rel_file_path}";')

        lines.append(f"    }}")
        lines.append("")

    # ---- 2. Config/ ディレクトリのクラス生成 ----
    lines.append("    /// <summary>")
    lines.append("    /// ゲーム設定 TOML ファイルのリソースパス定数。")
    lines.append("    /// </summary>")
    lines.append("    public static class Config")
    lines.append("    {")
    lines.append('        /// <summary>設定ファイルルートディレクトリ名。</summary>')
    lines.append('        public const string Directory = @"Config";')

    config_files = _scan_directory(_CONFIG_ROOT)
    # まずファイル名定数（Arena = "arena.toml" など）
    for file_path in config_files:
        stem_name = _to_pascal(file_path.stem)
        lines.append("")
        lines.append(f'        /// <summary>{file_path.name} 設定ファイル名。</summary>')
        lines.append(f'        public const string {stem_name} = "{file_path.name}";')

    # 次に相対パス定数（ArenaToml = @"Config\arena.toml" など）
    for file_path in config_files:
        rel_file_path = f"Config\\{file_path.name}"
        stem_name = _to_pascal(file_path.stem)
        ext = file_path.suffix.lstrip(".").capitalize()
        const_name = f"{stem_name}{ext}"
        lines.append("")
        lines.append(f'        /// <summary>{file_path.name} の相対パス。</summary>')
        lines.append(f'        public const string {const_name} = @"{rel_file_path}";')

    lines.append("    }")
    lines.append("")

    # ---- 3. ルートフォルダ定数 ----
    lines.append('    /// <summary>リソースルートディレクトリ名。</summary>')
    lines.append('    public const string ResourceDirectory = "Resource";')
    lines.append("")
    lines.append('    /// <summary>設定ファイルルートディレクトリ名。</summary>')
    lines.append('    public const string ConfigDirectory = "Config";')
    lines.append("}")
    lines.append("")

    return "\n".join(lines)


# ---- メイン ------------------------------------------------------------------

def main() -> None:
    print(f"[ResGen] リソースルート: {_RESOURCE_ROOT}")
    print(f"[ResGen] 設定ルート:     {_CONFIG_ROOT}")

    new_content = generate_code()

    _OUTPUT_FILE.parent.mkdir(parents=True, exist_ok=True)

    if _OUTPUT_FILE.exists():
        existing = _OUTPUT_FILE.read_text(encoding="utf-8")
        if existing == new_content:
            print(f"[ResGen] ResourcePath.g.cs は最新です。スキップします。")
            return

    _OUTPUT_FILE.write_text(new_content, encoding="utf-8", newline="\n")
    print(f"[ResGen] 生成完了: {_OUTPUT_FILE}")


if __name__ == "__main__":
    main()
