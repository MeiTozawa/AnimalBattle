using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace AnimalBattle.Generators;

/// <summary>
/// <c>[Require&lt;T&gt;]</c> (および <c>[Require(typeof(T))]</c>) 属性が付与された型を
/// コンパイル時にスキャンし、Flecs.NET の <c>With</c> トレイト登録コードを自動生成する
/// Incremental Source Generator。
/// </summary>
/// <remarks>
/// <c>Assembly.GetTypes()</c> や <c>MethodInfo.MakeGenericMethod()</c> を用いた実行時リフレクションは
/// トリミング / Native AOT 環境で動作が保証されないため (IL2026 / IL2060 / IL3050)、
/// 本ジェネレーターはコンパイル時に対象型を確定し、静的なジェネリック呼び出しのみで構成される
/// ソースコードを出力します。利用者は <c>[Require&lt;T&gt;]</c> を付与するだけで済み、
/// プラグイン側の手動登録は不要になります。
/// </remarks>
[Generator(LanguageNames.CSharp)]
public sealed class RequireComponentGenerator : IIncrementalGenerator
{
    private const string GenericAttributeMetadataName = "AnimalBattle.Components.RequireAttribute`1";
    private const string BaseAttributeMetadataName = "AnimalBattle.Components.RequireAttribute";

    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        IncrementalValuesProvider<RequirePair> genericPairs = context.SyntaxProvider
            .ForAttributeWithMetadataName(
                GenericAttributeMetadataName,
                predicate: static (node, _) => node is TypeDeclarationSyntax,
                transform: static (ctx, _) => CreatePairs(ctx, useGenericArgument: true))
            .SelectMany(static (pairs, _) => pairs);

        IncrementalValuesProvider<RequirePair> basePairs = context.SyntaxProvider
            .ForAttributeWithMetadataName(
                BaseAttributeMetadataName,
                predicate: static (node, _) => node is TypeDeclarationSyntax,
                transform: static (ctx, _) => CreatePairs(ctx, useGenericArgument: false))
            .SelectMany(static (pairs, _) => pairs);

        IncrementalValueProvider<ImmutableArray<RequirePair>> collected =
            genericPairs.Collect().Combine(basePairs.Collect())
                .Select(static (both, _) => both.Left.AddRange(both.Right));

        context.RegisterSourceOutput(collected, static (spc, items) => Execute(spc, items));
    }

    private static ImmutableArray<RequirePair> CreatePairs(GeneratorAttributeSyntaxContext ctx, bool useGenericArgument)
    {
        if (ctx.TargetSymbol is not INamedTypeSymbol targetSymbol)
        {
            return ImmutableArray<RequirePair>.Empty;
        }

        ImmutableArray<RequirePair>.Builder builder = ImmutableArray.CreateBuilder<RequirePair>();

        foreach (AttributeData attribute in ctx.Attributes)
        {
            ITypeSymbol? requiredType = useGenericArgument
                ? GetGenericRequiredType(attribute)
                : GetTypeofRequiredType(attribute);

            if (requiredType is null)
            {
                continue;
            }

            builder.Add(new RequirePair(targetSymbol, requiredType));
        }

        return builder.ToImmutable();
    }

    private static ITypeSymbol? GetGenericRequiredType(AttributeData attribute)
    {
        if (attribute.AttributeClass is { IsGenericType: true } attributeClass &&
            attributeClass.TypeArguments.Length == 1)
        {
            return attributeClass.TypeArguments[0];
        }

        return null;
    }

    private static ITypeSymbol? GetTypeofRequiredType(AttributeData attribute)
    {
        if (attribute.AttributeClass is { IsGenericType: true })
        {
            // ジェネリック版は BaseAttributeMetadataName にもマッチしてしまうため除外する。
            return null;
        }

        if (attribute.ConstructorArguments.Length == 1 &&
            attribute.ConstructorArguments[0] is { Kind: TypedConstantKind.Type, Value: ITypeSymbol typeSymbol })
        {
            return typeSymbol;
        }

        return null;
    }

    private static void Execute(SourceProductionContext context, ImmutableArray<RequirePair> pairs)
    {
        if (pairs.IsDefaultOrEmpty)
        {
            return;
        }

        // (対象型, 必須型) の重複を除去し、対象型 → 必須型の順で安定ソートする。
        var uniquePairs = new SortedSet<(string Target, string Required)>(PairComparer.Instance);
        foreach (RequirePair pair in pairs)
        {
            string target = pair.Target.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            string required = pair.Required.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            uniquePairs.Add((target, required));
        }

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("// このファイルは RequireComponentGenerator によって [Require<T>] 属性から自動生成されます。");
        sb.AppendLine("// 手動で編集しないでください。");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("using Flecs.NET.Core;");
        sb.AppendLine();
        sb.AppendLine("namespace AnimalBattle.Plugins;");
        sb.AppendLine();
        sb.AppendLine("/// <summary>");
        sb.AppendLine("/// <c>[Require&lt;T&gt;]</c> 属性から自動生成された Flecs.NET <c>With</c> 関係の登録処理。");
        sb.AppendLine("/// エンティティに対象コンポーネントが追加された際、必須コンポーネントが自動的に付与されます。");
        sb.AppendLine("/// </summary>");
        sb.AppendLine("internal static class RequireComponentRegistry");
        sb.AppendLine("{");
        sb.AppendLine("    /// <summary>");
        sb.AppendLine("    /// スキャンされた全ての Require 関係を Flecs.NET ワールドへ登録します。");
        sb.AppendLine("    /// </summary>");
        sb.AppendLine("    /// <param name=\"world\">登録先の Flecs.NET ワールド</param>");
        sb.AppendLine("    internal static void RegisterAll(World world)");
        sb.AppendLine("    {");

        foreach ((string target, string required) in uniquePairs)
        {
            sb.AppendLine(
                $"        world.Component<{target}>().Entity.Add(Ecs.With, world.Component<{required}>().Entity);");
        }

        sb.AppendLine("    }");
        sb.AppendLine("}");

        context.AddSource("RequireComponentRegistry.g.cs", sb.ToString());
    }

    private readonly struct RequirePair(ITypeSymbol target, ITypeSymbol required)
    {
        public ITypeSymbol Target { get; } = target;
        public ITypeSymbol Required { get; } = required;
    }

    private sealed class PairComparer : IComparer<(string Target, string Required)>
    {
        public static readonly PairComparer Instance = new();

        public int Compare((string Target, string Required) x, (string Target, string Required) y)
        {
            int targetCompare = string.CompareOrdinal(x.Target, y.Target);
            return targetCompare != 0 ? targetCompare : string.CompareOrdinal(x.Required, y.Required);
        }
    }
}
